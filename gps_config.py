import serial
import time

s = serial.Serial('/dev/ttyTHS1', 9600, timeout=2)

# Commande UBX pour activer toutes les constellations
# CFG-GNSS : GPS + SBAS + Galileo + BeiDou + GLONASS
ubx = bytes([
    0xB5, 0x62, 0x06, 0x3E, 0x3C, 0x00,
    0x00, 0x00, 0x20, 0x07,
    0x00, 0x08, 0x10, 0x00, 0x01, 0x00, 0x01, 0x01,  # GPS
    0x01, 0x01, 0x03, 0x00, 0x01, 0x00, 0x01, 0x01,  # SBAS
    0x02, 0x04, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01,  # Galileo
    0x03, 0x08, 0x10, 0x00, 0x01, 0x00, 0x01, 0x01,  # BeiDou
    0x04, 0x00, 0x08, 0x00, 0x00, 0x00, 0x01, 0x01,  # IMES
    0x05, 0x00, 0x03, 0x00, 0x01, 0x00, 0x01, 0x01,  # QZSS
    0x06, 0x08, 0x0E, 0x00, 0x01, 0x00, 0x01, 0x01,  # GLONASS
    0x8A, 0x41
])
s.write(ubx)
print("Constellations activées")
s.close()
